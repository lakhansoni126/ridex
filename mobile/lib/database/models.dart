import 'package:isar/isar.dart';

part 'models.g.dart'; // Will be generated by build_runner

@collection
class Vehicle {
  Id id = Isar.autoIncrement;

  late String name;
  late String brand;
  String? model;
  int? year;
  double initialOdometerKm = 0.0;

  @Backlink(to: 'vehicle')
  final rides = IsarLinks<Ride>();
}

@collection
class Ride {
  Id id = Isar.autoIncrement;

  late DateTime startTime;
  DateTime? endTime;

  // Statistics
  double distance = 0.0; // in kilometers
  double durationSeconds = 0.0;
  double avgSpeed = 0.0; // km/h
  double topSpeed = 0.0; // km/h
  /// Optional g-force peak from crash detection (legacy lean field kept for schema continuity).
  double maxLeanAngle = 0.0;

  // Weather Snapshot
  String? weatherCondition;
  double? temperatureCelsius;

  // Relationship to points
  @Backlink(to: 'ride')
  final points = IsarLinks<RidePoint>();

  // Relationship to Vehicle
  final vehicle = IsarLink<Vehicle>();
}

@collection
class RidePoint {
  Id id = Isar.autoIncrement;

  late double latitude;
  late double longitude;
  late double speed; // km/h
  late double heading;
  late double altitude;
  late double accuracy;
  late DateTime timestamp;

  // The ride this point belongs to
  final ride = IsarLink<Ride>();
}

/// Offline buffer for group-ride / location-share points awaiting API sync.
@collection
class PendingLocationPoint {
  Id id = Isar.autoIncrement;

  /// `ride` or `share`
  late String targetType;

  /// Ride ID or location-share ID
  late String targetId;

  late double latitude;
  late double longitude;
  double? speedMps;
  double? heading;
  double? accuracyM;
  String? status;
  late DateTime recordedAt;
  late DateTime createdAt;

  bool synced = false;
}
